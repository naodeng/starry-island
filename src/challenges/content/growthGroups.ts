import type { ChallengeGrowthDefinition } from '../domain/growth';

function growthTasks(groupId: string) {
  return [
    { id: `${groupId}/basic-01` },
    { id: `${groupId}/basic-02` },
    { id: `${groupId}/advanced-01` },
    { id: `${groupId}/advanced-02` },
    { id: `${groupId}/high-01` },
  ] as const;
}

function unitGroup(id: string, grade: number, subject: 'chinese' | 'math' | 'english', unitNumber: number): ChallengeGrowthDefinition {
  const unitId = `grade-${grade}/term-1/${subject}/unit-${String(unitNumber).padStart(2, '0')}`;
  return {
    id,
    kind: 'unit',
    grade,
    semester: 1,
    subject,
    sourceUnitIds: [unitId],
    tasks: growthTasks(id),
  };
}

function grade2Term1StageGroup(
  id: string,
  subject: 'chinese' | 'math' | 'english',
  stage: NonNullable<ChallengeGrowthDefinition['stage']>,
  unitNumbers: readonly number[],
): ChallengeGrowthDefinition {
  return {
    id,
    kind: 'semester',
    grade: 2,
    semester: 1,
    subject,
    sourceUnitIds: unitNumbers.map((unitNumber) =>
      `grade-2/term-1/${subject}/unit-${String(unitNumber).padStart(2, '0')}`),
    stage,
    tasks: growthTasks(id),
  };
}

